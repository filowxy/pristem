const dict: Record<Lang, Record<string, string>> = { 'zh-CN': zh, 'en-US': en };
const KEY = 'pristem.lang';
let current: Lang = 'zh-CN';
try {
  const saved = localStorage.getItem(KEY);
  if (saved === 'en-US' || saved === 'zh-CN') current = saved;
} catch { /* storage unavailable */ }

const listeners = new Set<() => void>();
export function getLang(): Lang { return current; }
export function subscribe(cb: () => void): () => void {
  listeners.add(cb);
  return () => listeners.delete(cb);
}
export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
  listeners.forEach((l) => l());
  document.documentElement.lang = next === 'zh-CN' ? 'zh-CN' : 'en';
}
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dict[current][key] ?? dict['zh-CN'][key]
    ?? dict[current]['common.contentUnavailable'] ?? dict['zh-CN']['common.contentUnavailable']
    ?? 'Content unavailable';
  // Both placeholder shapes are supported: the frozen UX_SPEC appendix uses
  // `{name}`, older keys use `{{name}}`.
  if (vars) for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{{${k}}}`, String(v)).replaceAll(`{${k}}`, String(v));
  }
  return s;
}
export function useI18n(): (key: string, vars?: Record<string, string | number>) => string {
  useSyncExternalStore(subscribe, getLang, getLang);
  return t;
}
